// Turns prompts/youtube-review-prompts.md (an export of the "Youtube Product Review Prompts" Google Doc)
// into lib/script-prompts.js. Run after replacing the .md:  node scripts/build-prompts.mjs
// The prompt text is kept word for word; only Google Docs' markdown escaping (\. \+ \[ ...) is removed.
import { readFileSync, writeFileSync } from 'node:fs';

const src = readFileSync(new URL('../prompts/youtube-review-prompts.md', import.meta.url), 'utf8').replace(/\r/g, '');
const lines = src.split('\n');
const clean = (t) => t.replace(/\\([.+\-[\]>#*_!()~`|])/g, '$1').replace(/\n{3,}/g, '\n\n').trim();

const marks = [];
lines.forEach((l, i) => {
  if (/^### .*Pre-prompt/.test(l)) marks.push({ i, key: 'pre' });
  const m = /^### .*Step (\d+)/.exec(l);
  if (m) marks.push({ i, key: `step${m[1]}`, n: Number(m[1]) });
  if (/^# .*Client Revisions Implementation/.test(l)) marks.push({ i, key: 'end' });
});
const opening = clean(lines.slice(0, marks[0].i).join('\n')).replace(/^#+\s*/, '').replace(/\*\*/g, '');
const TITLES = { 1: 'Intro (hook and setup)', 2: 'Platform overview', 3: 'Feature walkthrough', 4: 'Case study', 5: 'Real-world feedback', 6: 'Fit and pricing', 7: 'Editorial close', 8: 'Final assembly', 9: 'Entertainment edit' };
const out = { opening, pre: '', steps: [] };
for (let k = 0; k < marks.length - 1; k++) {
  const { i, key, n } = marks[k];
  const body = clean(lines.slice(i + 1, marks[k + 1].i).join('\n').replace(/\n---\s*$/, ''));
  if (key === 'pre') out.pre = body;
  else out.steps.push({ key, n, title: TITLES[n] || lines[i].replace(/[#*✅]/g, '').trim(), heading: clean(lines[i]).replace(/^#+\s*/, '').replace(/\*\*/g, '').replace('✅', '').trim(), prompt: body });
}
// Everything under "Client Revisions Implementation" is the prompt for the Implement revisions button.
// The export this file came from was cut off mid-sentence, so an unfinished last line is dropped.
const endAt = marks[marks.length - 1].i;
let rev = lines.slice(endAt + 1);
while (rev.length && !/[.!?:*)]\s*$/.test(rev[rev.length - 1].trim())) rev.pop();
out.revisions = clean(rev.join('\n'));
if (!out.pre || !out.revisions || out.steps.length !== 9 || out.steps.some((s, i) => s.n !== i + 1)) throw new Error('The prompt document does not have a pre-prompt and steps 1 to 9 in order.');
writeFileSync(new URL('../lib/script-prompts.js', import.meta.url),
  `// GENERATED by scripts/build-prompts.mjs from prompts/youtube-review-prompts.md. Do not edit by hand.\nexport default ${JSON.stringify(out, null, 2)};\n`);
console.log(`opening: ${out.opening}\npre-prompt: ${out.pre.length} chars\nrevisions: ${out.revisions.length} chars, ends: ${JSON.stringify(out.revisions.slice(-90))}`);
for (const s of out.steps) console.log(`${s.key}  ${s.title}  (${s.prompt.length} chars)  ${JSON.stringify(s.prompt.slice(0, 60))}`);
